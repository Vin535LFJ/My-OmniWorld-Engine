// Controlled staleness injection for the observation source.
//
// The interactive-loop research needs one number before any of MuJoCo, Cosmos
// or a VLA policy can be discussed honestly: how wrong does the belief layer
// get when the observation is not the current frame? No core change answers
// that -- the frame manifest is a plain list, so a lagged observation is a
// list whose entries point at earlier frames.
//
// This is NOT a generative world model: the pixels are the dataset's own.
// Lag L means "the observation the system receives at tick t is the frame
// that was current L ticks ago". That is what a persistence predictor
// ("nothing changes") would hand to the perception stack, and it is the
// cheapest honest control for any later real predictor: a predictor that
// emits frame(t) exactly must reproduce the lag-0 numbers.
//
// The truth side is untouched -- the annotation manifest still describes
// tick t -- so the metric measures input staleness, not truth drift.
import { readFileSync, writeFileSync } from 'node:fs';

function parseArgs(argv) {
  const out = { frames: '', lag: 0, out: '' };
  for (let i = 0; i < argv.length; ++i) {
    const a = argv[i];
    if (a === '--frames') out.frames = argv[++i];
    else if (a === '--lag') out.lag = Number(argv[++i]);
    else if (a === '--out') out.out = argv[++i];
    else throw new Error(`unknown argument '${a}'`);
  }
  if (!out.frames || !out.out) throw new Error('--frames and --out are required');
  if (!Number.isInteger(out.lag) || out.lag < 0) {
    throw new Error(`--lag must be a non-negative integer (got ${out.lag})`);
  }
  return out;
}

function parseManifest(text) {
  const header = [];
  const paths = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (line === '') continue;
    if (line.startsWith('#')) { header.push(line); continue; }
    if (line.includes('=')) { header.push(line); continue; }
    paths.push(line);
  }
  if (paths.length === 0) throw new Error('manifest lists no frames');
  return { header, paths };
}

const args = parseArgs(process.argv.slice(2));
const { header, paths } = parseManifest(readFileSync(args.frames, 'utf8'));

// Clamp at the head: a tick with no earlier frame gets the earliest available
// one. Inventing a frame would be a silent change to the measurement.
const lagged = paths.map((_, i) => paths[Math.max(0, i - args.lag)]);
const lines = [
  `# lagged observation manifest (lag=${args.lag})`,
  `# source: ${args.frames}`,
  '# generated by tools/stale_frames.mjs -- the pixels are original dataset frames,',
  '# only their ordering in time is changed.',
  ...header.filter((l) => !l.startsWith('#')),
  ...lagged,
  '',
];
writeFileSync(args.out, lines.join('\n'));

console.log(JSON.stringify({
  lag: args.lag,
  frames: paths.length,
  first: lagged[0],
  last: lagged[lagged.length - 1],
  out: args.out,
}));
